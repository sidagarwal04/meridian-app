const I18nContext = createContext<{ lang: string; setLang: (lang: string) => void; t: (key: string) => string }>({
  lang: "en",
  setLang: () => undefined,
  t: (key) => DICTS.en[key] ?? key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState("en");
  useEffect(() => {
    const stored = loadLang();
    if (DICTS[stored]) setLangState(stored);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo(
    () => ({
      lang,
      setLang: (next: string) => {
        setLangState(next);
        saveLang(next);
      },
      t: (key: string) => DICTS[lang]?.[key] ?? DICTS.en[key] ?? key,
    }),
    [lang]
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
